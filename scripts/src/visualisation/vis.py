    def plotAveragePerformance(
        self,
        exp_keys,
        results_dir: str = "lipinski_cross_feature_predictions",
        pred_set: str = "rdkit",
        group_feats: bool = True,
        save_path: str | Path | None = None,
        save_fname: str = "avg_embedding_grouped_bar_pearson_r",
        dpi: int = 300,
    ):
        paths = getPaths()
        results_root = paths["prediction_output_dirs"][results_dir]

        # Accept either:
        # 1) list/tuple of full experiment keys: ["pred_rdkit_tr_chemberta", ...]
        # 2) dict mapping label -> full key: {"chemberta": "pred_rdkit_tr_chemberta", ...}
        if isinstance(exp_keys, dict):
            exp_items = [(str(label), str(key)) for label, key in exp_keys.items()]
        else:
            exp_items = []
            for key in exp_keys:
                key = str(key)
                if "_tr_" in key:
                    label = key.split("_tr_", 1)[1]
                else:
                    label = key
                exp_items.append((label, key))

        # Load each experiment's Pearson_r
        exp_perf = {}
        train_labels = []
        for tr_lab, k in exp_items:
            p = results_root[k] / f"{k}.csv"
            df = pd.read_csv(p, index_col=0)[["Pearson_r"]].rename(
                columns={"Pearson_r": tr_lab}
            )
            exp_perf[tr_lab] = df
            train_labels.append(tr_lab)

        # Build descriptor-level table: one column per trainer + average across all.
        desc_perf_df = pd.concat([exp_perf[label] for label in train_labels], axis=1)
        desc_perf_df["average_across_all"] = desc_perf_df.mean(axis=1, skipna=True)

        # Compute entity means (group-level or descriptor-level)
        if group_feats:
            entity_map = getGroups(pred_set)
            entity_label = "Group"
        else:
            entity_map = {
                str(desc): [str(desc)] for desc in desc_perf_df.index.astype(str)
            }
            entity_label = "Feature"

        group_rows = {}
        for gname, members in entity_map.items():
            row = {}
            for tr_lab, df in exp_perf.items():
                present = [m for m in members if m in df.index]
                row[tr_lab] = df.loc[present, tr_lab].mean() if present else np.nan
            group_rows[gname] = row

        group_bar_df = pd.DataFrame.from_dict(group_rows, orient="index")
        group_bar_df["average_across_all"] = group_bar_df.mean(axis=1, skipna=True)

        # Plot grouped bars
        plot_cols = train_labels + ["average_across_all"]
        x = np.arange(len(group_bar_df.index))
        n = len(plot_cols)
        bar_w = 0.85 / n

        colour_map = dict(self.colour_map)
        colour_map["average_across_all"] = "#FFFFFF"

        fig, ax = plt.subplots(figsize=(16, 7))
        for i, c in enumerate(plot_cols):
            offset = (i - (n - 1) / 2) * bar_w
            is_avg = c == "average_across_all"
            ax.bar(
                x + offset,
                group_bar_df[c].to_numpy(dtype=float),
                width=bar_w,
                label=c,
                color=colour_map.get(c, "#7F7F7F"),
                edgecolor="black",
                linewidth=0.6,
                alpha=0.9,
                hatch="///" if is_avg else None,
            )

        ax.set_xticks(x)
        ax.set_xticklabels(group_bar_df.index, rotation=45, ha="right")
        ax.set_ylabel("Pearson_r")
        ax.set_title(
            f"{pred_set.upper()} {entity_label} Performance by Embedding Trainer (+ Average)"
        )
        ax.set_ylim(0, 1.05)
        ax.grid(axis="y", linestyle="--", alpha=0.3)
        ax.legend(
            ncol=1,
            frameon=False,
            loc="center left",
            bbox_to_anchor=(1.01, 0.5),
            borderaxespad=0.0,
        )
        plt.tight_layout(rect=[0, 0, 0.88, 1])

        if save_path is None:
            save_path = paths["imp_dirs"]["results_dir"] / f"{results_dir}"
            print(save_path)
        save_path = Path(save_path)
        save_path.mkdir(parents=True, exist_ok=True)

        fig.savefig(save_path / f"{save_fname}.png", dpi=dpi, bbox_inches="tight")
        plt.close(fig)

        # ----- Boxplots: descriptor-level performance distributions -----
        box_rows = []
        box_metrics = train_labels + ["average_across_all"]
        for group_name, members in entity_map.items():
            present = [m for m in members if m in desc_perf_df.index]
            if not present:
                continue
            group_slice = desc_perf_df.loc[present, box_metrics]
            for metric in box_metrics:
                vals = group_slice[metric].dropna()
                for val in vals:
                    box_rows.append(
                        {
                            "group": group_name,
                            "metric": metric,
                            "pearson_r": float(val),
                        }
                    )

        if box_rows:
            box_df = pd.DataFrame(box_rows)

            box_palette = dict(self.colour_map)
            box_palette["average_across_all"] = "#000000"

            # Combined plot: all groups
            fig_all, ax_all = plt.subplots(figsize=(18, 8))
            sns.boxplot(
                data=box_df,
                x="group",
                y="pearson_r",
                hue="metric",
                hue_order=box_metrics,
                whis=(0, 100),
                showfliers=False,
                palette=box_palette,
                ax=ax_all,
            )
            ax_all.set_xticklabels(ax_all.get_xticklabels(), rotation=45, ha="right")
            ax_all.set_ylim(0, 1.05)
            ax_all.set_xlabel(f"{pred_set.upper()} descriptor {entity_label.lower()}")
            ax_all.set_ylabel("Pearson_r")
            ax_all.set_title(
                f"{pred_set.upper()} Descriptor-Level Performance by {entity_label}"
            )
            ax_all.grid(axis="y", linestyle="--", alpha=0.3)
            ax_all.legend(
                title="Metric",
                loc="center left",
                bbox_to_anchor=(1.01, 0.5),
                frameon=False,
                ncol=1,
            )
            fig_all.tight_layout(rect=[0, 0, 0.88, 1])
            fig_all.savefig(
                save_path / f"{save_fname}_boxplot_all_groups.png",
                dpi=dpi,
                bbox_inches="tight",
            )
            plt.close(fig_all)

            if group_feats:
                # Individual plot per group
                for group_name in sorted(box_df["group"].unique()):
                    group_df = box_df[box_df["group"] == group_name]
                    if group_df.empty:
                        continue

                    fig_g, ax_g = plt.subplots(figsize=(12, 6))
                    sns.boxplot(
                        data=group_df,
                        x="metric",
                        y="pearson_r",
                        order=box_metrics,
                        whis=(0, 100),
                        showfliers=False,
                        palette=box_palette,
                        ax=ax_g,
                    )
                    ax_g.set_xticklabels(
                        ax_g.get_xticklabels(), rotation=45, ha="right"
                    )
                    ax_g.set_ylim(0, 1.05)
                    ax_g.set_xlabel("Metric")
                    ax_g.set_ylabel("Pearson_r")
                    ax_g.set_title(f"{pred_set.upper()} Group: {group_name}")
                    ax_g.grid(axis="y", linestyle="--", alpha=0.3)
                    fig_g.tight_layout()

                    safe_group_name = "".join(
                        ch if ch.isalnum() or ch in ("-", "_") else "_"
                        for ch in group_name
                    )
                    fig_g.savefig(
                        save_path / f"{save_fname}_boxplot_{safe_group_name}.png",
                        dpi=dpi,
                        bbox_inches="tight",
                    )
                    plt.close(fig_g)

        return group_bar_df

    def plotRFVsShapImportance(
        self,
        shap_bundle_path: str | Path,
        rf_importance_csv: str | Path,
        train_feat: str,
        save_path: str | Path,
        save_fname: str = "rf_vs_shap_importance",
        figsize: tuple = (7, 7),
        point_size: int = 8,
        alpha: float = 0.25,
        dpi: int = 300,
    ) -> pd.DataFrame:
        """
        Compare RF feature importance vs average absolute SHAP in one scatter plot.

        Expected inputs
        ---------------
        shap_bundle_path:
            Joblib bundle produced by shapAnalysisAll with key "shap_by_desc".
        rf_importance_csv:
            CSV where rows are input features and columns are descriptor importances
            (e.g., "Importance_MolWt_rdkit", ...).

        Returns
        -------
        pd.DataFrame
            Long dataframe with columns:
            ["rf", "shap", "rf_s", "shap_s"] after alignment and cleaning.
        """
        shap_bundle_path = Path(shap_bundle_path)
        rf_importance_csv = Path(rf_importance_csv)
        save_path = Path(save_path)
        save_path.mkdir(parents=True, exist_ok=True)

        shap_by_desc, feat_explain, _, _, _ = self._load_shap_bundle(shap_bundle_path)
        if shap_by_desc is None or feat_explain is None:
            raise FileNotFoundError(
                f"Could not load SHAP bundle from: {shap_bundle_path}"
            )

        # Build feature-by-descriptor SHAP importance matrix
        feature_names = feat_explain.columns.astype(str).tolist()
        shap_imp_df = pd.DataFrame(
            {desc: np.abs(vals).mean(axis=0) for desc, vals in shap_by_desc.items()},
            index=feature_names,
        )

        # Load RF importance matrix
        fi_df = pd.read_csv(rf_importance_csv, index_col=0)

        # Standardize descriptor column names so matrices align
        shap_imp_df = shap_imp_df.rename(columns=lambda c: str(c).replace("_model", ""))
        fi_df = fi_df.rename(columns=lambda c: str(c).replace("Importance_", ""))

        # Align rows/cols strictly
        common_idx = fi_df.index.intersection(shap_imp_df.index).sort_values()
        common_cols = fi_df.columns.intersection(shap_imp_df.columns).sort_values()

        rf = fi_df.reindex(index=common_idx, columns=common_cols)
        sh = shap_imp_df.reindex(index=common_idx, columns=common_cols)

        if rf.shape != sh.shape:
            raise ValueError(f"Mismatch after alignment: rf={rf.shape}, sh={sh.shape}")
        if rf.empty:
            raise ValueError(
                "No overlapping rows/columns between RF and SHAP matrices."
            )

        long_df = pd.DataFrame(
            {
                "rf": rf.to_numpy().ravel(),
                "shap": sh.to_numpy().ravel(),
            }
        )
        long_df = long_df.replace([np.inf, -np.inf], np.nan).dropna()
        if long_df.empty:
            raise ValueError("All aligned RF/SHAP pairs are NaN/Inf after cleaning.")

        rf_min, rf_max = long_df["rf"].min(), long_df["rf"].max()
        sh_min, sh_max = long_df["shap"].min(), long_df["shap"].max()

        if np.isclose(rf_max, rf_min):
            long_df["rf_s"] = 0.0
        else:
            long_df["rf_s"] = (long_df["rf"] - rf_min) / (rf_max - rf_min)

        if np.isclose(sh_max, sh_min):
            long_df["shap_s"] = 0.0
        else:
            long_df["shap_s"] = (long_df["shap"] - sh_min) / (sh_max - sh_min)

        fig, ax = plt.subplots(figsize=figsize)
        ax.scatter(
            long_df["rf_s"],
            long_df["shap_s"],
            s=point_size,
            alpha=alpha,
            color=self.colour_map.get(train_feat, "#000000"),
        )
        ax.plot([0, 1], [0, 1], "k--", lw=1)
        ax.set_xlabel("RF importance (scaled)")
        ax.set_ylabel("Mean |SHAP| (scaled)")
        ax.set_title("RF vs SHAP importance agreement")
        ax.grid(alpha=0.8)
        fig.tight_layout()
        fig.savefig(save_path / f"{save_fname}.png", dpi=dpi, bbox_inches="tight")
        plt.close(fig)

        return long_df

    def plotTrueVsPred(
        self,
        true_path: str | Path,
        pred_path: str | Path,
        true_col: str | None = None,
        pred_col: str | None = None,
        save_plot: bool = False,
        save_path: str | Path = Path("./"),
        save_fname: str = "true_vs_pred_joint_kde",
        figsize: tuple[float, float] = (7, 7),
        point_size: int = 18,
        alpha: float = 0.45,
        feat: str | None = None,
        save_top_error_mols: bool = True,
        top_error_n: int = 9,
        dpi: int = 300,
    ) -> pd.DataFrame:
        true_df = pd.read_csv(true_path, index_col=0)
        pred_df = pd.read_csv(pred_path, index_col=0)

        common_ids = pred_df.index.intersection(true_df.index)
        true_df = true_df.loc[common_ids]
        pred_df = pred_df.loc[common_ids]

        true_col = true_col or true_df.columns[0]
        pred_col = pred_col or pred_df.columns[0]

        plot_df = (
            pd.DataFrame(
                {
                    "true": pd.to_numeric(true_df[true_col], errors="coerce"),
                    "pred": pd.to_numeric(pred_df[pred_col], errors="coerce"),
                },
                index=common_ids,
            )
            .replace([np.inf, -np.inf], np.nan)
            .dropna()
        )

        if plot_df.empty:
            raise ValueError("No finite true/pred pairs found after alignment.")

        plot_df.index.name = "MolID"
        plot_df["difference"] = plot_df["pred"] - plot_df["true"]
        plot_df["abs_difference"] = plot_df["difference"].abs()

        if save_top_error_mols and (save_plot or self.save_all):
            save_path = Path(save_path)
            save_path.mkdir(parents=True, exist_ok=True)

            top_error_df = plot_df.nlargest(top_error_n, "abs_difference").copy()
            top_error_df = top_error_df.rename(
                columns={
                    "true": "true_val",
                    "pred": "pred_val",
                }
            )

            all_fps = {}
            for molid in plot_df.index:
                try:
                    smi = molid2Smiles(molid)
                    mol = Chem.MolFromSmiles(smi)
                    if mol is not None:
                        all_fps[molid] = MACCSkeys.GenMACCSKeys(mol)
                except Exception:
                    continue

            smiles = []
            mols = []
            legends = []
            avg_tanimoto_similarities = []
            for molid, row in top_error_df.iterrows():
                try:
                    smi = molid2Smiles(molid)
                except Exception:
                    smi = np.nan
                smiles.append(smi)

                mol = Chem.MolFromSmiles(smi) if isinstance(smi, str) else None
                if mol is not None:
                    mols.append(mol)

                fp = all_fps.get(molid)
                other_fps = [
                    other_fp
                    for other_id, other_fp in all_fps.items()
                    if other_id != molid
                ]
                if fp is not None and other_fps:
                    sims = DataStructs.BulkTanimotoSimilarity(fp, other_fps)
                    avg_tanimoto = float(np.mean(sims))
                else:
                    avg_tanimoto = np.nan
                avg_tanimoto_similarities.append(avg_tanimoto)

                if mol is not None:
                    legends.append(
                        f"{molid}\n\n"
                        f"T={row['true_val']:.1f} P={row['pred_val']:.1f} D={row['difference']:.1f}\n\n"
                        f"Avg MACCS Tanimoto={avg_tanimoto:.3f}"
                    )

            top_error_df["SMILES"] = smiles
            top_error_df["avg_tanimoto_to_prediction_set"] = avg_tanimoto_similarities
            top_error_df[
                [
                    "true_val",
                    "pred_val",
                    "difference",
                    "abs_difference",
                    "avg_tanimoto_to_prediction_set",
                    "SMILES",
                ]
            ].to_csv(
                save_path / f"{save_fname}_top_abs_errors.csv",
                index_label="MolID",
            )

            if mols:
                grid_img = Draw.MolsToGridImage(
                    mols[:top_error_n],
                    molsPerRow=3,
                    subImgSize=(360, 280),
                    legends=legends[:top_error_n],
                    legendFontSize=24,
                )
                grid_img.save(save_path / f"{save_fname}_top_abs_errors_mols.png")

        def _calc_metrics(df: pd.DataFrame) -> tuple[float, float, float]:
            if len(df) < 2:
                return np.nan, np.nan, np.nan
            return (
                pearsonr(df["true"], df["pred"])[0],
                r2_score(df["true"], df["pred"]),
                mean_squared_error(df["true"], df["pred"]) ** 0.5,
            )

        p75_cutoff = plot_df["true"].quantile(0.75)
        p75_df = plot_df[plot_df["true"] <= p75_cutoff]
        true_mean = plot_df["true"].mean()
        mean_window_df = plot_df[
            plot_df["true"].between(true_mean * 0.75, true_mean * 1.25)
        ]

        pearson_r, r2, rmse = _calc_metrics(plot_df)
        pearson_r_p75, r2_p75, rmse_p75 = _calc_metrics(p75_df)
        pearson_r_mean_window, r2_mean_window, rmse_mean_window = _calc_metrics(
            mean_window_df
        )

        fig = plt.figure(figsize=(figsize[0] * 3, figsize[1]))
        gs = fig.add_gridspec(
            2,
            3,
            height_ratios=(4, 1),
            width_ratios=(1, 1, 1),
            hspace=0.18,
            wspace=0.22,
        )

        panel_specs = [
            (plot_df, "Full range", (pearson_r, r2, rmse), 0),
            (p75_df, "P75 true BP", (pearson_r_p75, r2_p75, rmse_p75), 1),
            (
                mean_window_df,
                "True BP within 25% of mean",
                (pearson_r_mean_window, r2_mean_window, rmse_mean_window),
                2,
            ),
        ]

        for panel_df, panel_title, metrics, col_idx in panel_specs:
            ax_scatter = fig.add_subplot(gs[0, col_idx])
            ax_table = fig.add_subplot(gs[1, col_idx])
            ax_table.axis("off")

            if panel_df.empty:
                ax_scatter.set_title(f"{panel_title}\nNo data")
                ax_scatter.axis("off")
                continue

            ax_scatter.scatter(
                panel_df["true"],
                panel_df["pred"],
                s=point_size,
                alpha=alpha,
                color=(
                    self._getColour(feat) if feat is not None else self.default_colour
                ),
                edgecolors="none",
            )

            lim_min = min(panel_df["true"].min(), panel_df["pred"].min())
            lim_max = max(panel_df["true"].max(), panel_df["pred"].max())
            pad = (lim_max - lim_min) * 0.05
            if np.isclose(pad, 0):
                pad = 1.0
            limits = (lim_min - pad, lim_max + pad)

            ax_scatter.plot(limits, limits, "k--", lw=1)
            if len(panel_df) >= 2:
                slope, intercept = np.polyfit(panel_df["true"], panel_df["pred"], deg=1)
                fit_x = np.array(limits)
                ax_scatter.plot(
                    fit_x, slope * fit_x + intercept, color="#d62728", lw=1.5
                )

            ax_scatter.set_xlim(limits)
            ax_scatter.set_ylim(limits)
            ax_scatter.set_aspect("equal", adjustable="box")
            ax_scatter.set_xlabel(f"True {true_col}")
            ax_scatter.set_ylabel(f"Predicted {pred_col}")
            ax_scatter.set_title(
                f"{panel_title}\nRF Property Prediction (TR: {feat}, PR: {true_col})"
            )

            table = ax_table.table(
                cellText=[
                    [
                        f"{metrics[0]:.3f}",
                        f"{metrics[1]:.3f}",
                        f"{metrics[2]:.3f}",
                    ]
                ],
                colLabels=["Pearson r", "R2", "RMSE"],
                cellLoc="center",
                loc="center",
            )
            table.auto_set_font_size(False)
            table.set_fontsize(7)
            table.scale(1, 1.25)

            for spine in ("right", "top"):
                ax_scatter.spines[spine].set_visible(False)

        self._savePlot(
            save_plot=save_plot,
            save_path=save_path,
            save_fname=save_fname,
            dpi=dpi,
            description="true-vs-pred",
            fig=fig,
        )

        return plot_df


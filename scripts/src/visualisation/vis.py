    def plotFeatureImportance(
        self,
        data: pd.DataFrame,
        x_col: str = "Importance",
        y_col: str = "Feature",
        ascending=False,
        top_n: int = None,
        title: str = None,
        title_fontsize: int = 16,
        label_fontsize: int = 14,
        tick_fontsize: int = 12,
        figsize: tuple = (10, 8),
        save_plot: bool = False,
        save_path: Union[Path, str] = None,
        save_fname: str = "feature_importance",
        dpi: int = 400,
    ):
        """
        Generates a bar plot visualising feature importance scores for a given model.

        This function sorts and plots feature importance values, allowing visual
        interpretation of which features contribute most (or least) to model
        performance. It can optionally display only the top N most important features
        and save the resulting plot as an image.

        Parameters
        ----------
        data : pd.DataFrame
                            DataFrame containing the feature names and their
                            corresponding importance values.
        x_col : str (optional)
                            Name of the column containing numerical feature
                            importance values.
                            Default = "Importance".
        y_col : str (optional)
                            Name of the column containing feature names.
                            Default = "Feature".
        ascending : bool (optional)
                            Whether to sort the features in ascending order.
                            Default = False.
        top_n : int (optional)
                            Number of top features to display in the plot.
                            Default = None.
        title : str (optional)
                            Title of the feature importance plot.
                            Default = None.
        title_fontsize : int (optional)
                            Font size for the plot title.
                            Default = 16.
        label_fontsize : int (optional)
                            Font size for axis labels.
                            Default = 14.
        tick_fontsize : int (optional)
                            Font size for tick labels.
                            Default = 12.
        figsize : tuple (optional)
                            Figure size as (width, height) in inches.
                            Default = (10, 8).
        save_plot : bool (optional)
                            Whether to save the generated plot as an image.
                            Default = False.
        save_path : str, Path (optional)
                            Directory to save the plot to if `save_plot=True`.
                            Default = None.
        save_fname : str (optional)
                            Filename to save the plot under (without extension).
                            Default = "feature_importance".
        dpi : int (optional)
                            Dots per inch (image resolution) for the saved plot.
                            Default = 400.

        Returns
        -------
        None
                            Displays the feature importance plot and optionally saves
                            it to the specified directory.
        """

        # Sorting values by the x-column
        data = data.sort_values(by=x_col, ascending=ascending)

        # If specified, look at top_n number of features
        if top_n:
            data = data.head(top_n)

        # Setting the colour map
        palette = sns.color_palette("tab10", n_colors=len(data))
        colour_map = dict(zip(data[y_col], palette))

        # Plotting the figure
        plt.figure(figsize=figsize)
        sns.barplot(
            data=data,
            x=x_col,
            y=y_col,
            palette=colour_map,
            dodge=False,
            hue=y_col,
            legend=False,
        )

        plt.title(title, fontsize=title_fontsize)
        plt.ylabel(y_col, fontsize=label_fontsize)
        plt.xlabel(x_col.capitalize(), fontsize=label_fontsize)

        plt.xticks(fontsize=tick_fontsize, rotation=45)
        plt.yticks(fontsize=tick_fontsize)
        plt.tight_layout()

        self._savePlot(
            save_plot=save_plot,
            save_path=save_path,
            save_fname=save_fname,
            dpi=dpi,
            description="feature importance plot",
        )

        plt.show()

    def plotMultiTaskPerformance(
        self,
        data: pd.DataFrame,
        x_col: str,
        y_col: str,
        ascending: bool = False,
        top_n: int = None,
        subset: str = None,
        figsize: tuple = (10, 8),
        title: str = "Multi-Task Performance",
        title_fontsize: int = 16,
        label_fontsize: int = 14,
        tick_fontsize: int = 12,
        save_plot: bool = False,
        save_path: Path = None,
        save_fname: str = "multi-task_performance",
        dpi: int = 400,
    ):
        """
        Generates a horizontal bar chart visualising multi-task model performance
        across different feature representations.

        This plot shows how models trained on one feature set perform when
        predicting features from another, allowing comparison of cross-representation
        transfer performance. The data can optionally be filtered by descriptor name
        or limited to the top-performing features.

        Parameters
        ----------
        data : pd.DataFrame
                            DataFrame containing cross-feature performance values,
                            where rows correspond to predicted features and columns
                            include performance metrics.
        x_col : str
                            Name of the column containing the numerical performance
                            metric to plot (e.g., "Pearson_r" or "R2").
        y_col : str
                            Name of the column or label representing the predicted
                            feature set (used for the y-axis label).
        ascending : bool (optional)
                            Whether to sort the data in ascending order of the
                            performance metric.
                            Default = False.
        top_n : int (optional)
                            Number of top (or bottom, if ascending=True) features
                            to display in the plot.
                            Default = None.
        subset : str (optional)
                            Filters the data to include only features containing
                            this string (case-insensitive).
                            Default = None.
        figsize : tuple (optional)
                            Size of the figure as (width, height) in inches.
                            Default = (10, 8).
        title : str (optional)
                            Title of the bar chart.
                            Default = "Multi-Task Performance".
        title_fontsize : int (optional)
                            Font size for the plot title.
                            Default = 16.
        label_fontsize : int (optional)
                            Font size for axis labels.
                            Default = 14.
        tick_fontsize : int (optional)
                            Font size for tick labels.
                            Default = 12.
        save_plot : bool (optional)
                            Whether to save the generated plot as an image.
                            Default = False.
        save_path : str, Path (optional)
                            Directory to save the plot to if `save_plot=True`.
                            Default = None.
        save_fname : str (optional)
                            Filename to save the plot under (without extension).
                            Default = "multi-task_performance".
        dpi : int (optional)
                            Dots per inch (image resolution) for the saved plot.
                            Default = 400.

        Returns
        -------
        None
                            Displays the bar chart and optionally saves it to the
                            specified directory.
        """

        # Look for subset of desciptors containing the string "subset"
        if subset:
            data = data[
                data.index.astype(str).str.contains(subset, case=False, na=False)
            ]

        # Ensure numerical values, drop N/A and sort values
        data = data.copy()
        data[x_col] = pd.to_numeric(data[x_col], errors="coerce")
        data = data.dropna(subset=[x_col])
        data = data.sort_values(by=x_col, ascending=ascending)

        # If specified, look at top_n number of features
        if top_n:
            data = data.head(top_n)

        # Plotting the figure
        plt.figure(figsize=figsize)
        plt.barh(data.index, data[x_col].values)
        plt.title(title, fontsize=title_fontsize)

        plt.xlabel(x_col.capitalize(), fontsize=label_fontsize)
        plt.ylabel(y_col, fontsize=label_fontsize)

        plt.yticks(fontsize=tick_fontsize)
        plt.xticks(fontsize=tick_fontsize)

        plt.tight_layout()

        self._savePlot(
            save_plot=save_plot,
            save_path=save_path,
            save_fname=save_fname,
            dpi=dpi,
            description="multi-task plot",
        )

        plt.show()

    def computeGroupPerf(
        self,
        data: pd.DataFrame,
        descriptor_groups: dict,
        metrics: list[str],
        exclude: list[str] = None,
    ) -> pd.DataFrame:
        """
        Computes the average performance metrics for each descriptor group.

        This function takes a set of descriptors grouped by category (e.g.,
        from RDKit or Mordred) and calculates the mean value of the specified
        performance metrics across all descriptors within each group. It is
        typically used to summarise feature set performance before generating
        grouped bar or radar plots.

        Parameters
        ----------
        data : pd.DataFrame
                            DataFrame containing descriptor names (as the index)
                            and corresponding performance metric values.
        descriptor_groups : dict
                            Dictionary mapping descriptor group names to lists of
                            descriptor columns. Can be generated using the
                            `getGroups()` function for RDKit or Mordred descriptors.
        metrics : list[str]
                            One or more performance metrics to average across
                            descriptor groups (e.g., ["Pearson_r", "r2"]).
        exclude : list[str] (optional)
                            List of descriptors to exclude from the averaging
                            calculation.
                            Default = None.

        Returns
        -------
        pd.DataFrame
                            DataFrame containing the average values of the
                            specified metrics for each descriptor group. Each
                            row represents a descriptor group, and each column
                            corresponds to an averaged metric.
        """

        # Exclude descriptors, if specified
        if exclude is None:
            exclude = []

        # Calculate group performances
        print(descriptor_groups)
        group_perf = {}
        for group, descs in descriptor_groups.items():
            valid = [d for d in descs if d in data.index and d not in exclude]
            if valid:
                group_perf[group] = data.loc[valid, metrics].mean()

        print(group_perf)

        out = pd.DataFrame.from_dict(group_perf, orient="index")
        out = out[metrics]
        out = out.rename(columns={m: f"avg_{m}" for m in metrics})

        return out

    def plotGroupRadar(
        self,
        group_perf_df,
        title: str = "Radar Plot",
        figsize: tuple | None = (15, 11),
        title_fontsize: int = 16,
        label_fontsize: int = 11,
        tick_fontsize: int = 9,
        save_plot: bool = False,
        save_path: Union[str, Path] = None,
        save_fname: str = "group_radar",
        dpi: int = 400,
        wrap_labels: bool = True,
        wrap_width: int = 14,
        rotate_labels: bool = True,
        metadata: dict = {},
        c1=None,
        c2=None,
    ):
        """
        Generates a radar (spider) plot visualising descriptor group performances
        with dual scales for comparison (0–1 and 0.5–1).

        The radar plot highlights how each descriptor group contributes to overall
        model performance, allowing easier comparison of strong and weak feature
        sets across groups.

        Parameters
        ----------
        group_perf_df : pd.DataFrame
                            DataFrame containing descriptor group performance
                            values, typically produced by the `computeGroupPerf()`
                            function. The index should contain group names, and
                            the first column should contain performance values.
        title : str (optional)
                            Title for the radar plot.
                            Default = "Radar Plot".
        figsize : tuple (optional)
                            Size of the figure as (width, height) in inches.
                            Default = (10, 10).
        title_fontsize : int (optional)
                            Font size for the plot title.
                            Default = 16.
        label_fontsize : int (optional)
                            Font size for the axis (descriptor) labels.
                            Default = 12.
        tick_fontsize : int (optional)
                            Font size for radial tick labels.
                            Default = 10.
        save_plot : bool (optional)
                            Whether to save the generated radar plot as an image.
                            Default = False.
        save_path : str, Path (optional)
                            Directory to save the plot to if `save_plot=True`.
                            Default = None.
        save_fname : str (optional)
                            Filename to save the plot under (without extension).
                            Default = "group_radar".
        dpi : int (optional)
                            Dots per inch (image resolution) for the saved plot.
                            Default = 400.

        Returns
        -------
        None
                            Displays the radar plot and optionally saves it to
                            the specified directory.
        """

        # --- Basic validation ---
        if group_perf_df is None or group_perf_df.empty:
            raise ValueError("group_perf_df is empty. Nothing to plot.")

        # Use first numeric column by default
        col0 = group_perf_df.select_dtypes(include="number").columns
        if len(col0) == 0:
            raise ValueError("group_perf_df has no numeric columns to plot.")
        values = group_perf_df[col0[0]].to_numpy(dtype=float)

        labels = group_perf_df.index.astype(str).tolist()

        # Optional: make labels nicer (break underscores and wrap)
        pretty_labels = []
        for lab in labels:
            lab = lab.replace("_rdkit", "").replace("_mordred", "")
            lab2 = lab.replace("_", " ")
            if wrap_labels:
                lab2 = "\n".join(textwrap.wrap(lab2, width=wrap_width))
            pretty_labels.append(lab2)

        # Close the loop
        values = np.append(values, values[0])

        n = len(labels)
        angles = np.linspace(0, 2 * np.pi, n, endpoint=False)
        angles = np.append(angles, angles[0])

        # Colours
        palette = sns.color_palette("tab10")
        c1 = c1 or palette[0]
        c2 = c2 or palette[3]

        fig = plt.figure(figsize=figsize)

        # -------------------------
        # Axis 1 (0–1 scale)
        # -------------------------
        ax1 = fig.add_subplot(111, polar=True)

        ax1.plot(angles, values, linewidth=2, color=c1, label="0–1 scale", alpha=0.65)
        ax1.fill(angles, values, alpha=0.18, color=c1)

        ax1.set_ylim(0, 1.0)
        ticks_c1 = np.arange(0, 1.01, 0.1)
        ax1.set_yticks(ticks_c1)
        ax1.set_yticklabels(
            [f"{t:.1f}" if t > 0 else "" for t in ticks_c1],
            fontsize=tick_fontsize,
            fontweight="bold",
            color=c1,
        )

        ax1.set_xticks(angles[:-1])
        ax1.set_xticklabels(pretty_labels, fontsize=label_fontsize, fontweight="bold")

        # Rotate labels so they follow the circle (reduces overlap a lot)
        if rotate_labels:
            for lbl, ang in zip(ax1.get_xticklabels(), angles[:-1]):
                ang_deg = np.degrees(ang)
                # keep text upright-ish
                if 90 < ang_deg < 270:
                    lbl.set_rotation(ang_deg + 180)
                    lbl.set_ha("right")
                else:
                    lbl.set_rotation(ang_deg)
                    lbl.set_ha("left")
                lbl.set_va("center")

        # Put c1 radial labels at top
        ax1.set_rlabel_position(90)

        # Slightly pad the plot from the figure edge
        ax1.tick_params(axis="x", pad=14)

        # -------------------------
        # Axis 2 (0.5–1 scale)
        # -------------------------
        ax2 = fig.add_subplot(111, polar=True, frame_on=False)
        ax2_values = np.clip(values, 0.5, 1.0)
        ax2.plot(
            angles,
            ax2_values,
            linewidth=2,
            color=c2,
            linestyle="--",
            label="0.5–1 scale",
            alpha=0.6,
        )
        ax2.fill(angles, ax2_values, alpha=0.10, color=c2)

        ax2.set_ylim(0.5, 1.0)
        ticks_c2 = np.arange(0.5, 1.01, 0.1)
        ax2.set_yticks(ticks_c2)

        # FIX: use tick_fontsize (not title_fontsize) + slightly lighter weight
        ax2.set_yticklabels(
            [f"{t:.2f}" for t in ticks_c2],
            fontsize=tick_fontsize,
            fontweight="semibold",
            color=c2,
        )

        ax2.set_xticks([])
        ax2.set_xticklabels([])
        ax2.set_rlabel_position(270)

        # Make the red labels a bit closer to the circle to reduce clutter
        ax2.tick_params(axis="y", pad=2)

        # Legend (keep it inside a bit so it doesn't collide)
        handles1, labels1 = ax1.get_legend_handles_labels()
        handles2, labels2 = ax2.get_legend_handles_labels()
        ax1.legend(
            handles1 + handles2,
            labels1 + labels2,
            loc="upper right",
            bbox_to_anchor=(1.18, 1.12),
            fontsize=label_fontsize,
            frameon=False,
        )

        ax1.set_title(title, fontsize=title_fontsize, fontweight="bold", pad=28)

        # Layout tweak (polar plots often need manual spacing)
        plt.subplots_adjust(top=0.88, bottom=0.08, left=0.08, right=0.92)

        self._savePlot(
            save_plot=save_plot,
            save_path=save_path,
            save_fname=save_fname,
            dpi=dpi,
            description="descriptor-grouped radar plot",
            metadata=metadata,
        )

    def plotMemberBar(
        self,
        perf_df,
        group_map: dict[str, list[str]],
        group_name: str,
        value_col: str | None = None,
        title: str | None = None,
        figsize: tuple | None = None,
        title_fontsize: int = 16,
        label_fontsize: int = 11,
        tick_fontsize: int = 9,
        save_plot: bool = False,
        save_path: Union[str, Path] = None,
        save_fname: str | None = None,
        dpi: int = 400,
        wrap_labels: bool = True,
        wrap_width: int = 14,
        rotate_labels: bool = True,
        metadata: dict = {},
    ):
        if group_name not in group_map:
            raise ValueError(f"Group '{group_name}' not found in group_map")

        members = group_map[group_name]

        present = [m for m in members if m in perf_df.index]
        missing = [m for m in members if m not in perf_df.index]

        if not present:
            raise ValueError(
                f"No members from group '{group_name}' are present in perf_df.index"
            )

        if missing:
            print(f"Skipping missing group members for '{group_name}': {missing}")

        member_df = perf_df.loc[present].copy()

        if value_col is None:
            numeric_cols = member_df.select_dtypes(include="number").columns
            if len(numeric_cols) == 0:
                raise ValueError("perf_df has no numeric columns to plot.")
            value_col = numeric_cols[0]

        value_series = pd.to_numeric(member_df[value_col], errors="coerce")
        finite_mask = np.isfinite(value_series.to_numpy(dtype=float))

        if not finite_mask.all():
            skipped_nonfinite = member_df.index[~finite_mask].astype(str).tolist()
            print(
                f"Skipping non-finite '{value_col}' values for group '{group_name}': "
                f"{skipped_nonfinite}"
            )

        member_df = member_df.loc[finite_mask].copy()
        if member_df.empty:
            raise ValueError(
                f"Group '{group_name}' has no finite '{value_col}' values to plot."
            )
        member_df[value_col] = pd.to_numeric(member_df[value_col], errors="coerce")
        member_df = member_df.sort_values(by=value_col, ascending=False)

        values = member_df[value_col].to_numpy(dtype=float)
        labels = member_df.index.astype(str).tolist()
        if figsize is None:
            figsize = (
                max(11, min(0.85 * len(labels), 120)),
                11,
            )

        pretty_labels = []
        for lab in labels:
            lab = lab.replace("_rdkit", "").replace("_mordred", "")
            lab2 = lab.replace("_", " ")
            if wrap_labels:
                lab2 = "\n".join(textwrap.wrap(lab2, width=wrap_width))
            pretty_labels.append(lab2)

        fig = plt.figure(figsize=figsize)
        ax = fig.add_subplot(111)

        bar_colours = [self._getColour(label) for label in labels]
        x_positions = np.arange(len(labels))

        ax.bar(
            x_positions,
            values,
            color=bar_colours,
            edgecolor="black",
            linewidth=0.8,
            alpha=0.85,
        )

        ax.set_xticks(x_positions)
        rotation = 70 if rotate_labels else 0
        ha = "right" if rotate_labels else "center"
        ax.set_xticklabels(
            pretty_labels,
            fontsize=label_fontsize,
            fontweight="bold",
            rotation=rotation,
            ha=ha,
        )

        ax.set_ylabel(value_col, fontsize=label_fontsize, fontweight="bold")
        ax.tick_params(axis="y", labelsize=tick_fontsize)
        ax.set_axisbelow(True)
        ax.grid(axis="y", linestyle="--", alpha=0.35)

        ax.set_ylim(0.0, 1.1)

        plot_title = title or f"{group_name} member performance"
        ax.set_title(plot_title, fontsize=title_fontsize, fontweight="bold", pad=18)

        plt.subplots_adjust(top=0.88, bottom=0.22, left=0.10, right=0.96)

        self._savePlot(
            save_plot=save_plot,
            save_path=save_path,
            save_fname=save_fname or f"{group_name}_member_bar",
            dpi=dpi,
            description=f"{group_name} member bar plot",
            fig=fig,
            metadata=metadata,
        )

    def plotPoorPredictionFeatureDistribution(
        self,
        perf_df,
        full_features: str | Path,
        group_map: dict[str, list[str]],
        group_name: str,
        value_col: str = "Pearson_r",
        save_plot: bool = True,
        threshold: float = 0.6,
        save_path: str | Path = None,
    ):

        full_features = pd.read_csv(full_features, index_col=0)

        if group_name not in group_map:
            raise ValueError(f"Group '{group_name}' not found in group_map")

        members = group_map[group_name]
        poorly_performing_desc = []

        for desc in members:
            if desc not in perf_df.index:
                continue
            if desc not in full_features.columns:
                continue

            desc_perf = perf_df.loc[desc, value_col]
            if desc_perf < threshold:
                poorly_performing_desc.append(desc)

        for p_desc in poorly_performing_desc:
            desc_distribution = full_features[p_desc].dropna()

            plt.figure(figsize=(6, 4), dpi=150)
            plt.hist(desc_distribution, bins=40, edgecolor="black")
            plt.xlabel(p_desc)
            plt.ylabel("Count")
            plt.title(
                f"{p_desc} distribution\n{value_col}={perf_df.loc[p_desc, value_col]:.3f}"
            )
            plt.tight_layout()

            if save_plot:
                if save_path is None:
                    raise ValueError("save_path must be provided when save_plot=True")
                save_path = Path(save_path)

        if mode == "cum":
            out_of_range["low"] = colour_low

        for mask_key, color in out_of_range.items():
            ax.scatter(
                df.loc[masks[mask_key], x_col],
                df.loc[masks[mask_key], y_col],
                s=55,
                c=color,
                alpha=0.85,
                edgecolor="black",
                linewidth=0.25,
            )

        cbar_label = (
            f"Avg top-N {imp_type} importance"
            if mode == "avg"
            else f"Cum top-N {imp_type} importance"
        )
        out_handles = [
            Line2D(
                [0],
                [0],
                marker="o",
                linestyle="",
                markerfacecolor=colour_low,
                markeredgecolor="black",
                markersize=7,
                label=f"< {r_vmin}",
            ),
            Line2D(
                [0],
                [0],
                marker="o",
                linestyle="",
                markerfacecolor=colour_mid,
                markeredgecolor="black",
                markersize=7,
                label=f"> {r_vmax}",
            ),
            Line2D(
                [0],
                [0],
                marker="o",
                linestyle="",
                markerfacecolor=colour_high,
                markeredgecolor="black",
                markersize=7,
                label=f">> {r_high}",
            ),
        ]

        ax.plot([0, 1], [0, 1], "k--", lw=1)
        ax.set_xlim(xlim[0], xlim[1])
        ax.set_ylim(ylim[0], ylim[1])
        ax.set_xlabel(x_axis_label)
        ax.set_title(title)

        cbar = fig.colorbar(sc, ax=ax, fraction=0.046, pad=0.04)
        cbar.set_label(cbar_label)
        ax.legend(
            handles=out_handles,
            title="Out-of-range" if mode == "cum" else "Higher importance",
            bbox_to_anchor=(1.32, 1.0),
            loc="upper left",
            frameon=False,
            fontsize=8,
            title_fontsize=9,
        )


    def plotNumUniqueDescVsPerf(
        self,
        train_data: str | pd.DataFrame | Path,
        perf_data: str | pd.DataFrame | Path,
        desc_set: str | None = None,
        metric: str = "Pearson_r",
        wildcard: str = "*",
        ascending: bool = False,
        bin_size: int = 100,
        x_label: str = "Bin Number",
        y_label: str | None = None,
        title: str | None = None,
        figsize: tuple = (10, 5),
        rotation: int = 75,
        title_fontsize: int = 16,
        label_fontsize: int = 12,
        tick_fontsize: int = 10,
        color: str | None = None,
        observed: bool = False,
        top_n_bins: int | None = None,
        show_counts: bool = False,
        counts_label: str = "Count",
        save_plot: bool = False,
        save_path: str | Path | None = None,
        save_fname: str = "perf_vs_nunique_binned",
        dpi: int = 400,
    ) -> pd.DataFrame:
        """
        Plot average model performance per fixed-width bin of descriptor uniqueness.

        The function counts how many unique values each descriptor has in the training
        data, aligns with the per-descriptor performance table (``metric``), bins the
        descriptors by uniqueness (width = ``bin_size``), computes the mean performance
        per bin, and renders a bar chart. Returns the binned summary table.

        Parameters
        ----------
        train_data : str, pd.DataFrame, Path
                            Descriptor matrix (true values used for model training). Rows are samples;
                            columns are descriptor names.
        perf_data : str, pd.DataFrame, Path
                            Table of per-descriptor performance metrics. The index must contain
                            descriptor names; the chosen ``metric`` must be a column.
        desc_set : str or None, optional
                            Key into ``self.colour_map`` to choose a default color. Ignored if
                            ``color`` is provided directly. Default is None.
        metric : str, optional
                            Performance metric column to aggregate (e.g., "Pearson_r", "R2", "RMSE").
                            Default is "Pearson_r".
        wildcard : str, optional
                            Wildcard passed to ``_loadData`` when loading multiple files. Default is "*".
        ascending : bool, optional
                            If True, sort by uniqueness ascending before binning (affects intermediate
                            tables only). Default is False.
        bin_size : int, optional
                            Width of uniqueness bins. Default is 100.
        x_label : str, optional
                            X-axis label. Default is "Bin Number".
        y_label : str or None, optional
                            Y-axis label for averaged performance. Defaults to f"Average {metric}".
        title : str or None, optional
                            Plot title. Defaults to
                            f"Average {metric} vs Number of Unique Descriptor Values (bin size = {bin_size})".
        figsize : tuple, optional
                            Figure size in inches. Default is (10, 5).
        rotation : int, optional
                            X-tick label rotation in degrees. Default is 75.
        title_fontsize : int, optional
                            Title font size. Default is 16.
        label_fontsize : int, optional
                            Axis label font size. Default is 12.
        tick_fontsize : int, optional
                            Tick label font size. Default is 10.
        color : str or None, optional
                            Bar color. If None, and ``desc_set`` is provided and found in
                            ``self.colour_map``, that color is used; otherwise Matplotlib default.
        observed : bool, optional
                            Whether to drop empty categorical bins in groupby. Default is True.
        top_n_bins : int or None, optional
                            If provided, only the first N bins (left to right) are displayed.
                            Default is None.
        show_counts : bool, optional
                            If True, plot descriptor counts per bin on a secondary y-axis.
                            Default is False.
        counts_label : str, optional
                            Label for the counts axis if ``show_counts`` is True. Default is "Count".
        save_plot : bool, optional
                            Whether to save the figure via ``_savePlot``. Default is False.
        save_path : str or Path or None, optional
                            Directory for saving if ``save_plot=True``. Default is None.
        save_fname : str, optional
                            Filename (without extension) for saving. Default is "perf_vs_nunique_binned".
        dpi : int, optional
                            Dots per inch when saving. Default is 400.

        Returns
        -------
        pd.DataFrame
            Binned summary with columns:
            - ``n_unique_bin`` : interval for the uniqueness bin (e.g., (0, 100])
            - ``{metric}``     : mean performance in the bin
            - ``bin_num``      : integer label (1..N) for bin order
            - ``count``        : number of descriptors in the bin
        """
        # Load data
        train_df = loadData(df=train_data, index_col=0, wildcard=wildcard)
        perf_df = loadData(df=perf_data, index_col=0, wildcard=wildcard)

        # Keep only common descriptors
        common_cols = train_df.columns.intersection(perf_df.index)
        if len(common_cols) == 0:
            raise ValueError(
                "No common descriptor names found between training and performance data."
            )

        train_df = train_df[common_cols]
        perf_df = perf_df.loc[common_cols]

        # Uniqueness per descriptor
        desc_nunique = train_df.nunique()
        desc_nunique_df = pd.DataFrame({"n_unique": desc_nunique}).sort_values(
            by="n_unique", ascending=ascending
        )

        # Merge with performance
        merged_df = desc_nunique_df.merge(
            perf_df[[metric]], left_index=True, right_index=True, how="inner"
        )
        merged_df = merged_df.dropna(subset=["n_unique", metric])

        # Binning
        max_val = merged_df["n_unique"].max()
        if pd.isna(max_val) or max_val <= 0:
            raise ValueError(
                "Unable to determine bins: 'n_unique' is empty or non-positive."
            )
        bins = np.arange(0, max_val + bin_size, bin_size)
        if len(bins) < 2:
            bins = np.array([0, max_val])  # fallback to a single bin if needed

        merged_df["n_unique_bin"] = pd.cut(merged_df["n_unique"], bins=bins)

        # Aggregate per bin (mean performance + count)
        grp = merged_df.groupby("n_unique_bin", observed=observed)
        summary_df = grp[metric].mean().to_frame()
        summary_df["count"] = grp.size()
        summary_df = summary_df.reset_index().sort_values(by="n_unique_bin")
        summary_df["bin_num"] = np.arange(1, len(summary_df) + 1)

        # Optionally limit number of bins shown
        if top_n_bins is not None:
            summary_df = summary_df.head(top_n_bins)

        # Resolve color
        if color is None and desc_set is not None and hasattr(self, "colour_map"):
            color = self.colour_map.get(desc_set, None)

        # Labels / titles defaults
        if y_label is None:
            y_label = f"Average {metric}"
        if title is None:
            title = f"Average {metric} vs Number of Unique Descriptor Values"

        # Plot
        fig, ax1 = plt.subplots(figsize=figsize)

        sns.barplot(data=summary_df, x="bin_num", y=metric, color=color, ax=ax1)
        ax1.set_xlabel(
            f"{x_label}\n(bin size = {bin_size})",
            fontsize=label_fontsize,
            fontweight="bold",
        )
        ax1.set_ylabel(y_label, fontsize=label_fontsize, fontweight="bold")
        ax1.set_title(title, fontsize=title_fontsize, fontweight="bold")
        ax1.tick_params(axis="x", labelrotation=rotation, labelsize=tick_fontsize)
        ax1.tick_params(axis="y", labelsize=tick_fontsize)

        # Optional counts on secondary axis
        if show_counts:
            ax2 = ax1.twinx()
            ax2.plot(summary_df["bin_num"], summary_df["count"], marker="o")
            ax2.set_ylabel(counts_label, fontsize=label_fontsize)
            ax2.tick_params(axis="y", labelsize=tick_fontsize)

        plt.tight_layout()

        # Save if requested
        self._savePlot(
            save_plot=save_plot,
            save_path=save_path,
            save_fname=save_fname,
            dpi=dpi,
            description="binned performance vs uniqueness",
        )

        plt.show()
        return summary_df


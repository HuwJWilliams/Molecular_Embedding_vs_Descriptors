        sc = ax.scatter(
            df.loc[masks["inrange"], x_col],
            df.loc[masks["inrange"], y_col],
            s=55,
            c=df.loc[masks["inrange"], importance_col],
            cmap="viridis",
            vmin=r_vmin,
            vmax=r_vmax,
            alpha=0.85,
            edgecolor="black",
            linewidth=0.25,
        )

